// Copies the compiled sale contract (ABI + deployable bytecode) into the store, for the admin's "Deploy" button.
// Run after `npx hardhat compile`:  node scripts/export-artifact.js
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const src = path.join(__dirname, '..', 'contracts', 'PalladiumTokenSale.sol');
const art = require(path.join(__dirname, '..', 'artifacts', 'contracts', 'PalladiumTokenSale.sol', 'PalladiumTokenSale.json'));
const out = path.join(__dirname, '..', '..', 'src', 'lib', 'palladium', 'sale-artifact.json');
const sourceSha256 = crypto.createHash('sha256').update(fs.readFileSync(src)).digest('hex');
fs.writeFileSync(out, JSON.stringify({
  note: 'Generated by contracts/scripts/export-artifact.js from contracts/contracts/PalladiumTokenSale.sol. Do not edit by hand.',
  contractName: art.contractName, compiler: 'solc 0.8.28, optimizer 200 runs, evm cancun', sourceSha256,
  abi: art.abi, bytecode: art.bytecode,
}, null, 1) + '\n');
console.log('wrote', path.relative(process.cwd(), out), '| bytecode bytes', (art.bytecode.length - 2) / 2, '| source sha256', sourceSha256.slice(0, 16));
